export function casesForStandard(standardId) {
  if (!standardId) return professionalCases;
  return professionalCases.filter((item) => item.standards.includes(standardId));
}

export function getProfessionalCase(caseId) {
  return professionalCases.find((item) => item.id === caseId) || null;
}
