const enrichStandard = (standard) => {
  const guidance = guidanceById[standard.id] || {};
  const accountingStandard = standard.type === "accounting";
  return {
    ...standard,
    scope: guidance.scope || [standard.summary],
    recognitionMeasurement: guidance.recognitionMeasurement || (accountingStandard ? standard.requirements.slice(0, 2) : []),
    presentationDisclosure: guidance.presentationDisclosure || (accountingStandard ? standard.requirements.slice(2) : []),
    auditFocus: guidance.auditFocus || (!accountingStandard ? standard.requirements : []),
    judgments: guidance.judgments || [],
    relatedStandards: guidance.relatedStandards || [],
    references: guidance.references || (accountingStandard ? referencesFor("ifrs-ar-2025") : []),
    referenceLocators: accountingStandard ? getStandardReferenceLocators(standard.id) : [],
    locatorStatus: accountingStandard && getStandardReferenceLocators(standard.id).length ? "verified-attached" : accountingStandard ? "official-only" : "issuer-link",
    officialSourceIds: accountingStandard
      ? (standard.id === "SOCPA ZAKAT" ? ["socpa-accounting"] : ["socpa-accounting", "ifrs-navigator"])
      : ["socpa-professional", "iaasb-projects"],
  };
};

