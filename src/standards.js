const MAPPING_SCHEMA_VERSION = 1;
const FOREIGN_CURRENCY_STANDARD_ID = "IAS 21";

const uniqueIds = (ids) => [...new Set((ids || []).filter((id) => typeof id === "string" && standardsById.has(id)))];

const normalizeCurrencyCode = (value) => String(value || "").trim().toUpperCase();

const isForeignMonetaryAccount = (account) => {
  const currency = normalizeCurrencyCode(account?.currency);
  const functionalCurrency = normalizeCurrencyCode(account?.functionalCurrency || account?.balanceCurrency || "SAR");
  return account?.monetaryItem === true
    && /^[A-Z]{3}$/.test(currency)
    && /^[A-Z]{3}$/.test(functionalCurrency)
    && currency !== functionalCurrency;
};

const contextualAccountingIds = (account) => (
  isForeignMonetaryAccount(account) ? [FOREIGN_CURRENCY_STANDARD_ID] : []
);

const suggestedAccountingIds = (account) => {
  const candidates = Array.isArray(account?.suggestedStandardIds)
    ? account.suggestedStandardIds
    : Array.isArray(account?.standards)
      ? account.standards
      : [account?.standard];

  return uniqueIds([...candidates, ...contextualAccountingIds(account)])
    .filter((id) => standardsById.get(id)?.type === "accounting");
};

const suggestedAuditIds = (account) => uniqueIds(account?.auditStandards)
  .filter((id) => standardsById.get(id)?.type === "audit");

const normalizeMappingState = (mappingState) => ({
  schemaVersion: MAPPING_SCHEMA_VERSION,
  overrides: mappingState?.overrides && typeof mappingState.overrides === "object" && !Array.isArray(mappingState.overrides)
    ? { ...mappingState.overrides }
    : {},
  ...(mappingState?.lastBulkReview ? { lastBulkReview: { ...mappingState.lastBulkReview } } : {}),
  ...(mappingState?.review ? { review: { ...mappingState.review } } : {}),
});

const validReviewDecision = (override) => Boolean(
  override
  && typeof override === "object"
  && Array.isArray(override.standardIds)
  && override.standardIds.length > 0
  && typeof override.reviewer === "string"
  && override.reviewer.trim()
  && typeof override.rationale === "string"
  && override.rationale.trim()
  && Number.isFinite(Date.parse(override.reviewedAt || "")),
);

/**
 * Creates the small persisted state used for reviewer decisions. Only accounts
 * explicitly reviewed are stored; deterministic suggestions stay on the
 * generated trial-balance rows and are not duplicated in localStorage.
 */
export function createStandardMappings() {
  return { schemaVersion: MAPPING_SCHEMA_VERSION, overrides: {} };
}

/**
 * Resolves one account into one of three auditable states:
 * - suggested: the deterministic mapping is usable but has no manual override;
 * - reviewed: a reviewer explicitly accepted or changed the accounting links;
 * - review_required: the account has no usable mapping until a reviewer acts.
 */
export function resolveAccountMapping(account, mappingState = createStandardMappings()) {
  const accountId = account?.id == null ? "" : String(account.id);
  const accountingSuggestions = suggestedAccountingIds(account);
  const auditSuggestions = suggestedAuditIds(account);
  const contextualStandardIds = contextualAccountingIds(account);
  const override = accountId && mappingState?.overrides
    ? mappingState.overrides[accountId]
    : null;
  const hasValidOverride = validReviewDecision(override);

  if (hasValidOverride) {
    const accountingStandardIds = uniqueIds([...override.standardIds, ...contextualStandardIds])
      .filter((id) => standardsById.get(id)?.type === "accounting");
    const auditStandardIds = auditSuggestions;
    const effectiveStandardIds = uniqueIds([...accountingStandardIds, ...auditStandardIds]);

    return {
      accountId,
      status: "reviewed",
      isResolved: true,
      isReviewed: true,
      suggestedStandardIds: accountingSuggestions,
      suggestedAuditStandardIds: auditSuggestions,
      contextualStandardIds,
      accountingStandardIds,
      auditStandardIds,
      effectiveStandardIds,
      reviewer: override.reviewer || null,
      rationale: override.rationale || "",
      reviewedAt: override.reviewedAt || null,
      source: override.source || "manual",
    };
  }

  const hasUsableSuggestion = account?.mapped !== false && accountingSuggestions.length > 0;
  if (hasUsableSuggestion) {
    return {
      accountId,
      status: "suggested",
      isResolved: true,
      isReviewed: false,
      suggestedStandardIds: accountingSuggestions,
      suggestedAuditStandardIds: auditSuggestions,
      contextualStandardIds,
      accountingStandardIds: accountingSuggestions,
      auditStandardIds: auditSuggestions,
      effectiveStandardIds: uniqueIds([...accountingSuggestions, ...auditSuggestions]),
      reviewer: null,
      rationale: "",
      reviewedAt: null,
      source: "suggested",
    };
  }

  return {
    accountId,
    status: "review_required",
    isResolved: false,
    isReviewed: false,
    suggestedStandardIds: accountingSuggestions,
    suggestedAuditStandardIds: auditSuggestions,
    contextualStandardIds,
    accountingStandardIds: [],
    auditStandardIds: [],
    effectiveStandardIds: [],
    reviewer: null,
    rationale: "",
    reviewedAt: null,
    source: "suggested",
  };
}

/**
 * Persists one explicit reviewer decision without mutating the previous state.
 * A review decision must contain at least one valid accounting standard plus
 * reviewer identity, rationale, and a valid timestamp. Empty or anonymous
 * overrides remain unresolved and cannot open the reporting gate.
 */
export function applyMappingReview(mappingState, account, standardIds, metadata = {}) {
  if (account?.id == null || String(account.id).length === 0) {
    throw new TypeError("An account id is required to review a standards mapping.");
  }

  const state = normalizeMappingState(mappingState);
  const selectedIds = Array.isArray(standardIds)
    ? standardIds
    : resolveAccountMapping(account, state).suggestedStandardIds;
  const accountingStandardIds = uniqueIds(selectedIds)
    .filter((id) => standardsById.get(id)?.type === "accounting");
  const accountId = String(account.id);
  const reviewer = typeof metadata.reviewer === "string" ? metadata.reviewer.trim() : "";
  const rationale = typeof metadata.rationale === "string" ? metadata.rationale.trim() : "";
  const reviewedAt = metadata.reviewedAt || "";

  if (!accountingStandardIds.length) {
    throw new TypeError("At least one valid accounting standard is required for a mapping decision.");
  }
  if (!reviewer || !rationale || !Number.isFinite(Date.parse(reviewedAt))) {
    throw new TypeError("Reviewer, rationale, and a valid reviewedAt timestamp are required.");
  }

  return {
    ...state,
    overrides: {
      ...state.overrides,
      [accountId]: {
        standardIds: accountingStandardIds,
        reviewer,
        rationale,
        reviewedAt,
        source: metadata.source || "manual",
      },
    },
  };
}

/**
 * Reviews unresolved accounts against their existing suggestions. Existing
 * manual decisions are retained and the function never writes 5,000 automatic
 * suggestions into persisted state.
 */
export function bulkReviewMappings(accounts, mappingState = createStandardMappings(), metadata = {}) {
  let nextState = normalizeMappingState(mappingState);
  const allowedIds = Array.isArray(metadata.accountIds)
    ? new Set(metadata.accountIds.map(String))
    : null;
  let reviewedCount = 0;

  for (const account of accounts || []) {
    const resolution = resolveAccountMapping(account, nextState);
    if (resolution.status !== "review_required") continue;
    if (allowedIds && !allowedIds.has(resolution.accountId)) continue;
    if (!allowedIds && (account?.classificationConflict || account?.classificationSource === "unclassified-fallback")) continue;

    nextState = applyMappingReview(nextState, account, resolution.suggestedStandardIds, {
      reviewer: metadata.reviewer,
      rationale: metadata.rationale,
      reviewedAt: metadata.reviewedAt,
      source: metadata.source || "bulk-review",
    });
    reviewedCount += 1;
  }

  if (reviewedCount === 0) return nextState;

  return {
    ...nextState,
    lastBulkReview: {
      reviewer: typeof metadata.reviewer === "string" && metadata.reviewer.trim()
        ? metadata.reviewer.trim()
        : null,
      rationale: typeof metadata.rationale === "string" ? metadata.rationale.trim() : "",
      reviewedAt: metadata.reviewedAt || null,
      reviewedCount,
    },
  };
}

export function buildMappingMetrics(accounts, mappingState = createStandardMappings()) {
  const metrics = {
    accountCount: 0,
    total: 0,
    suggested: 0,
    auto: 0,
    reviewed: 0,
    reviewRequired: 0,
    resolved: 0,
    mapped: 0,
    unresolved: 0,
    mappingRate: 0,
    overrideCount: Object.keys(mappingState?.overrides || {}).length,
  };

  for (const account of accounts || []) {
    const { status } = resolveAccountMapping(account, mappingState);
    metrics.accountCount += 1;
    if (status === "reviewed") metrics.reviewed += 1;
    if (status === "suggested") metrics.suggested += 1;
    if (status === "review_required") metrics.reviewRequired += 1;
  }

  metrics.resolved = metrics.reviewed + metrics.suggested;
  metrics.total = metrics.accountCount;
  metrics.auto = metrics.suggested;
  metrics.mapped = metrics.resolved;
  metrics.unresolved = metrics.reviewRequired;
  metrics.mappingRate = metrics.accountCount
    ? Number(((metrics.resolved / metrics.accountCount) * 100).toFixed(1))
    : 100;

  return metrics;
}

export function getAccountStandardIds(account, mappingState = createStandardMappings(), options = {}) {
  const resolution = resolveAccountMapping(account, mappingState);
  if (resolution.status === "review_required" && options.includeSuggested) {
    return uniqueIds([...resolution.suggestedStandardIds, ...resolution.suggestedAuditStandardIds]);
  }
  return resolution.effectiveStandardIds;
}

