import { writeFile } from "node:fs/promises";

const engagementOwnedTables = Object.freeze([
  "source_files",
  "rejected_rows",
  "accounts",
  "trial_balance_lines",
  "journal_entries",
  "journal_lines",
  "mapping_sets",
  "mapping_rules",
  "calculation_runs",
  "derivations",
  "provenance_nodes",
  "derivation_inputs",
  "figures",
  "facts",
  "je_test_runs",
  "findings",
  "finding_dispositions",
  "materiality_versions",
  "misstatements",
  "opinion_assessments",
  "ai_proposals",
  "ai_claims",
  "ai_reviews",
]);

const appendOnlyTables = Object.freeze([
  ...engagementOwnedTables,
  "audit_log",
  "fs_lines",
]);

const statements = [
  `CREATE TRIGGER engagements_no_delete
BEFORE DELETE ON engagements
BEGIN
  SELECT RAISE(ABORT, 'engagements_cannot_be_deleted');
END;`,
  `CREATE TRIGGER engagements_archived_no_update
BEFORE UPDATE ON engagements
WHEN OLD.archived_at IS NOT NULL
BEGIN
  SELECT RAISE(ABORT, 'archived_engagement_is_read_only');
END;`,
  `CREATE TRIGGER engagements_identity_no_update
BEFORE UPDATE ON engagements
WHEN OLD.id <> NEW.id
  OR OLD.tenant_id <> NEW.tenant_id
  OR OLD.framework <> NEW.framework
  OR OLD.ruleset_version <> NEW.ruleset_version
  OR OLD.period_start <> NEW.period_start
  OR OLD.period_end <> NEW.period_end
BEGIN
  SELECT RAISE(ABORT, 'engagement_identity_is_immutable');
END;`,
];

for (const table of appendOnlyTables) {
  statements.push(`CREATE TRIGGER ${table}_no_update
BEFORE UPDATE ON ${table}
BEGIN
  SELECT RAISE(ABORT, '${table}_is_append_only');
END;`);
  statements.push(`CREATE TRIGGER ${table}_no_delete
BEFORE DELETE ON ${table}
BEGIN
  SELECT RAISE(ABORT, '${table}_is_append_only');
END;`);
}

for (const table of engagementOwnedTables) {
  statements.push(`CREATE TRIGGER ${table}_archived_insert_guard
BEFORE INSERT ON ${table}
WHEN EXISTS (
  SELECT 1 FROM engagements
  WHERE id = NEW.engagement_id AND archived_at IS NOT NULL
)
BEGIN
  SELECT RAISE(ABORT, 'archived_engagement_is_read_only');
END;`);
}

const output = [
  "-- Generated by scripts/generate-d1-guards.mjs.",
  "-- Historical engagement records are append-only; audit_log remains insertable after archive.",
  statements.join("\n--> statement-breakpoint\n"),
  "",
].join("\n");

await writeFile(new URL("../drizzle/0001_execution_guards.sql", import.meta.url), output, "utf8");
console.log(`Generated ${statements.length} D1 integrity triggers`);
